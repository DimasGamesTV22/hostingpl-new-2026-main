#!/usr/bin/env bash
#
# Поведенческая проверка выбора режима запуска.
#
# Запуск: bash panel/tools/check-mode.sh
#
# Главное, что нужно доказать: вложенный запуск из пункта меню
# (GAMEDOCK_NESTED=1) НЕ выбирает режим меню. Именно это ломало пункт
# «Установка панели» — он открывал меню заново вместо установки.
#
# Подгружаем install.sh (нижний код защищён проверкой BASH_SOURCE) и
# вызываем mode_is_menu напрямую.
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT" || exit 1

# shellcheck disable=SC1091
. ./deploy/install.sh >/dev/null 2>&1
set +eu

pass=0
fail=0

ok()  { pass=$((pass + 1)); printf '  \033[32mok\033[0m   %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf '  \033[31mFAIL\033[0m %s\n' "$1"; [[ $# -gt 1 ]] && printf '       %s\n' "$2"; return 0; }

# is_menu <SHOW_MENU> <GAMEDOCK_NESTED> <кол-во аргументов>
is_menu() {
    SHOW_MENU="$1" GAMEDOCK_NESTED="$2" mode_is_menu "${@:3}"
}

echo "=== ВЫБОР РЕЖИМА ==="

# 1. Регресс: вложенный запуск без флагов обязан дать установку.
if ! is_menu "" "1"; then
    ok "вложенный запуск без флагов → установка, а не меню"
else
    bad "вложенный запуск без флагов → установка" "открылось меню заново (исходный баг)"
fi

# 2. Явный --menu побеждает даже внутри вложенного запуска.
if is_menu "yes" "1"; then
    ok "явный --menu сильнее вложенного запуска"
else
    bad "явный --menu сильнее вложенного запуска" "явное требование проигнорировано"
fi

# 3. Без меток и без аргументов — меню (на терминале).
if is_menu "" ""; then
    ok "запуск без меток и без аргументов → меню"
else
    bad "запуск без меток и без аргументов → меню" "ожидался вход в меню"
fi

# 4. Есть аргументы — линейный запуск.
if ! is_menu "" "" --domain example.com; then
    ok "запуск с аргументами → линейный сценарий"
else
    bad "запуск с аргументами → линейный сценарий" "аргументы проигнорированы"
fi

# 5. Вложенный запуск с флагами — тоже линейный.
if ! is_menu "" "1" --domain example.com; then
    ok "вложенный запуск с флагами → линейный сценарий"
else
    bad "вложенный запуск с флагами → линейный сценарий" "открылось меню"
fi

# 6. Значение «0» считается заданным: не должно молча пропускать.
if ! is_menu "" "0"; then
    ok "GAMEDOCK_NESTED=0 тоже считается вложенным запуском"
else
    bad "GAMEDOCK_NESTED=0" "пустое-но-заданное значение открыло меню"
fi

echo
printf 'Пройдено: %d, провалено: %d\n' "$pass" "$fail"
[[ $fail -eq 0 ]]